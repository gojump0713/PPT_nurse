export function WorldMap({ markers = [] } = {}) {
  const graticule = [];
  for (let lon = -150; lon <= 150; lon += 30) {
    const [x] = project([lon, 0]);
    graticule.push(h('line', { x1: x, y1: 0, x2: x, y2: H, class: 'wm__grid' }));
  }
  for (let lat = -60; lat <= 60; lat += 30) {
    const [, y] = project([0, lat]);
    graticule.push(h('line', { x1: 0, y1: y, x2: W, y2: y, class: 'wm__grid' }));
  }

  const lands = Object.entries(LANDS).map(([key, coords]) =>
    h('polygon', { points: toPoints(coords), class: 'wm__land', 'data-land': key })
  );

  const markerEls = markers.map((m, i) => {
    const [x, y] = project([m.lon, m.lat]);
    // 두 마커가 지리적으로 가까울 수 있으므로 번호를 붙여 카드와 짝을 맞춘다
    const g = h('g.wm__marker', { dataset: { i: String(i) }, transform: `translate(${x.toFixed(1)},${y.toFixed(1)})` },
      h('circle', { r: 26, class: 'wm__pulse' }),
      h('circle', { r: 9, class: 'wm__pin' }),
      h('circle', { r: 3.4, class: 'wm__pin-core' }),
      h('text', { class: 'wm__no', x: 0, y: m.labelBelow ? 30 : -17, 'text-anchor': 'middle' }, String(i + 1).padStart(2, '0'))
    );
    g.pos = { x, y };
    return g;
  });

  const svg = h('svg.wm', { viewBox: `0 0 ${W} ${H}`, preserveAspectRatio: 'xMidYMid meet' },
    ...graticule, ...lands, ...markerEls
  );
  svg.markerEls = markerEls;
  svg.project = project;
  svg.size = { W, H };
  return svg;
}
